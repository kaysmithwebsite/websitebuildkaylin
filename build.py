def organizations_block():
    """The #giving-back section of the About page.

    Each entry states Kaylin's own involvement rather than describing what the
    organisation does: the brief asks for her participation, not an encyclopedia
    entry, and a generic charity blurb is the thing that makes a page like this
    read as filler. Names link to each organisation's official site. Logos stay
    off until both a file and written permission exist, because a charity logo
    is a trademark and showing one implies a relationship it has agreed to."""
    d = PAGES["organizations"]
    orgs = ORGS["organizations"]

    no_url = [o["name"] for o in orgs if not o.get("url")]
    if no_url:
        warn("organizations.json: %s %s no official URL, so the name renders as plain text "
             "rather than a guessed link." % (", ".join(no_url),
                                              "has" if len(no_url) == 1 else "have"))
    if not any(o.get("permission_confirmed") for o in orgs):
        warn("organizations.json: no logo permission is confirmed, so no charity logos are shown. "
             "Request each logo and written permission from the organisation, then set "
             "permission_confirmed and logo_path.")

    rows = []
    for o in orgs:
        logo = ""
        if o.get("logo_path") and o.get("permission_confirmed"):
            logo = ('<span class="org__logo"><img src="%s" alt="%s" height="30" '
                    'loading="lazy" decoding="async"></span>'
                    % (e(o["logo_path"]), e(o["name"])))
        if o.get("url"):
            name = ('<a href="%s" target="_blank" rel="noopener">%s'
                    '<span class="org__ext" aria-hidden="true">&#8599;</span>'
                    '<span class="visually-hidden"> (opens in a new tab)</span></a>'
                    % (e(o["url"]), e(o["name"])))
        else:
            name = e(o["name"])
        paras = "".join('<p class="org__b">%s</p>' % e(p) for p in o.get("involvement") or [])
        if not paras and not PRODUCTION:
            paras = placeholder("Involvement not supplied yet")
        rows.append('<article class="org">%s<div><h3 class="org__name">%s</h3>%s</div></article>'
                    % (logo, name, paras))

    br = ORGS.get("broader") or {}
    broader = ""
    if br.get("paragraphs"):
        broader = (
          '<div class="g12 giving__broader">'
            '<h3 class="label c3" data-reveal>%s</h3>'
            '<div class="c8 s5" data-reveal>%s</div>'
          '</div>'
        ) % (e(br.get("heading") or "Broader community involvement"),
             "".join("<p>%s</p>" % e(p) for p in br["paragraphs"]))

    return (
      '<section class="section tone-off" id="giving-back" aria-labelledby="gb-h">'
      '<div class="wrap">'
        '<div class="g12" style="margin-bottom:clamp(1.75rem,3.4vw,3rem)">'
          '<p class="label c12" data-reveal>%s</p>'
          '<h2 class="statement c7" id="gb-h" data-reveal>%s</h2>'
          '<div class="meta c4 s9 baseline" data-reveal>%s</div>'
        '</div>'
        '<div class="orgs" data-stagger>%s</div>'
        '%s'
      '</div></section>'
    ) % (e(d["eyebrow"]), e(d["headline"]),
         "".join("<p>%s</p>" % e(p) for p in ORGS["intro"]),
         "".join(rows), broader)


