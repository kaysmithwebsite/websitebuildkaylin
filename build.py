def build_gov_programs():
    """Federal, provincial and municipal programs that change what a purchase
    actually costs. Every entry carries an official source URL and no
    last_verified date, so the page states plainly that nothing here has been
    checked against the source by this build. Rules and dollar figures move;
    presenting them as settled would be the one thing this site must not do."""
    live   = [p for p in GOV["programs"] if p.get("active")]
    closed = [p for p in GOV["programs"] if not p.get("active")]

    def rows(p):
        pairs = [("Who it is for", p.get("who")),
                 ("What you get", p.get("benefit_summary")),
                 ("Eligibility", p.get("eligibility_summary"))]
        return "".join('<div class="prog__row"><dt>%s</dt><dd>%s</dd></div>'
                       % (lbl, e(val)) for lbl, val in pairs if val)

    def entry(p, n, ended=False):
        src = ""
        if p.get("source_url"):
            src = ('<p class="prog__src"><a class="tlink" href="%s" target="_blank" '
                   'rel="noopener">%s %s</a></p>'
                   % (e(p["source_url"]),
                      e("Official source: " + (p.get("official_source") or "government page")),
                      ARW))
        return ('<article class="prog%s" id="%s" data-reveal>'
                  '<p class="prog__meta"><span class="prog__n">%02d</span>'
                  '<span class="prog__jur">%s</span>%s</p>'
                  '<h3 class="prog__t">%s</h3>'
                  '<p class="prog__b">%s</p>'
                  '<dl class="prog__dl">%s</dl>%s'
                '</article>'
                % (" prog--ended" if ended else "", e(p["slug"]), n,
                   e(p.get("jurisdiction") or ""),
                   '<span class="prog__ended">No longer accepting applications</span>' if ended else "",
                   e(p["title"]), e(p.get("description") or ""), rows(p), src))

    groups = []
    n = 0
    for c in GOV["categories"]:
        inside = [p for p in live if p.get("category") == c["slug"]]
        if not inside:
            continue
        items = ""
        for p in inside:
            n += 1
            items += entry(p, n)
        groups.append(
          '<section class="section--sm" aria-labelledby="cat-%s"><div class="wrap">'
            '<div class="g12">'
              '<div class="c3" data-reveal>'
                '<h2 class="h3" id="cat-%s">%s</h2>'
                '<p class="meta mt-4">%s</p>'
              '</div>'
              '<div class="c8 s5 proglist">%s</div>'
            '</div>'
          '</div></section>' % (e(c["slug"]), e(c["slug"]), e(c["name"]),
                                e(c.get("intro") or ""), items))

    ended = ""
    if closed:
        items = ""
        for p in closed:
            n += 1
            items += entry(p, n, ended=True)
        ended = (
          '<section class="section--sm section tone-off" aria-labelledby="cat-closed">'
          '<div class="wrap"><div class="g12">'
            '<div class="c3" data-reveal>'
              '<h2 class="h3" id="cat-closed">Closed</h2>'
              '<p class="meta mt-4">Listed because people still ask about them and still find '
              'them written up elsewhere as though they were open.</p>'
            '</div>'
            '<div class="c8 s5 proglist">%s</div>'
          '</div></div></section>' % items)

    warn("government-programs.json has no last_verified date on any entry, so the programs page "
         "renders its not-yet-verified banner. Set last_verified per program once the figures "
         "have been checked against the official source.")

    body = (
      phero("Government Programs", "The money that is already on the table.",
            "Federal, provincial and municipal programs change what a purchase actually costs, "
            "and most of them are claimed by your lawyer or accountant rather than by you. "
            "Here is what exists, who it is for, and where the official rules live.",
            [("Home", "/"), ("Real Estate", "/real-estate/")], "Government Programs") +
      '<section class="section"><div class="wrap"><div class="g12">'
        '<div class="c7" data-reveal>%s</div>'
        '<div class="c4 s9" data-reveal>'
          '<p class="meta">Programs are grouped by what they are for rather than by which level '
          'of government runs them, because that is the order you meet them in. Amounts and '
          'thresholds are deliberately not printed here. They move, and a number frozen into a '
          'web page is worse than no number at all.</p>'
        '</div>'
      '</div></div></section>'
      '%s%s'
      '<section class="section--sm section" aria-label="How to use this"><div class="wrap">'
        '<div class="g12">'
          '<p class="label c3" data-reveal>Before you rely on any of this</p>'
          '<p class="formnote c8 s5" style="font-size:.8125rem">Eligibility for most of these '
          'turns on details that a summary cannot settle: how the CRA defines a first-time buyer, '
          'whose name is on title, what your spouse owned and when. Confirm your own position '
          'with the official source above, and take advice from a lawyer or accountant before '
          'acting. Kaylin can tell you which programs are worth investigating for your purchase '
          'and can bring in the right professional, and does not give tax or legal advice.</p>'
        '</div>'
      '</div></section>'
    ) % (verified_banner("Nothing on this page has been checked against the current official "
                         "source by this build."),
         "".join(groups), ended)

    page("real-estate/programs/index.html", "/real-estate/programs/",
         "Government Programs for Buyers and Owners | Kaylin Smith",
         "Federal, Ontario and Toronto programs that affect what a home purchase costs: "
         "the FHSA, Home Buyers' Plan, land transfer tax refunds, rebates and credits, with "
         "a link to the official source for each.",
         body, crumbs=[("Home", "/"), ("Real Estate", "/real-estate/")],
         priority=0.8, lastmod=TODAY)


