def fmt_date(iso, style="long"):
    try:
        d = datetime.date(*[int(x) for x in iso.split("-")])
    except Exception:
        return iso
    if style == "long":
        return d.strftime("%B %-d, %Y") if os.name != "nt" else d.strftime("%B %d, %Y")
    return d.strftime("%b %-d, %Y") if os.name != "nt" else d.strftime("%b %d, %Y")

