def field(name, label, kind="text", required=False, placeholder="", options=None,
          rule=None, boxed=False, autocomplete=None, value="", help_text="", idp=""):
    """idp namespaces the control id. The filter form is rendered twice on the
    listing pages (inline and in the mobile drawer); without a namespace the two
    copies would emit duplicate ids and break every label association."""
    fid = "f-" + (idp + "-" if idp else "") + slugify(name)
    req = " required" if required else ""
    reqmark = ' <span aria-hidden="true">*</span>' if required else ""
    ac = ' autocomplete="%s"' % e(autocomplete) if autocomplete else ""
    rl = ' data-rule="%s"' % e(rule) if rule else ""

    if kind == "select":
        opts = "".join('<option value="%s"%s>%s</option>'
                       % (e(v), " selected" if v == value else "", e(l)) for v, l in options)
        ctl = '<select class="select" id="%s" name="%s"%s%s>%s</select>' % (fid, e(name), req, ac, opts)
    elif kind == "textarea":
        ctl = ('<textarea class="textarea" id="%s" name="%s" placeholder="%s"%s%s>%s</textarea>'
               % (fid, e(name), e(placeholder), req, ac, e(value)))
    else:
        ctl = ('<input class="input" type="%s" id="%s" name="%s" placeholder="%s" value="%s"%s%s%s>'
               % (e(kind), fid, e(name), e(placeholder), e(value), req, ac, rl))

    hint = '<p class="formnote" style="margin-top:.5rem">%s</p>' % help_text if help_text else ""
    return ('<div class="field%s"><label class="field__label" for="%s">%s%s</label>%s%s'
            '<p class="field__error" id="%s-error" aria-live="polite"></p></div>'
            % (" field--boxed" if boxed else "", fid, e(label), reqmark, ctl, hint, fid))


