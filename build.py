# ------------------------------------------------------------------- utils
def e(s):
    return html.escape(u"" if s is None else unicode_str(s), quote=True)

def unicode_str(s):
    try:
        return s if isinstance(s, str) else str(s)
    except Exception:
        return str(s)

def money(n, cents=False):
    if n is None: return ""
    n = float(n)
    if cents:
        return "${:,.2f}".format(n)
    return "${:,.0f}".format(n)

def num(n):
    if n is None: return ""
    return "{:,}".format(int(n))

def slugify(s):
    s = re.sub(r"[^a-z0-9]+", "-", (s or "").lower()).strip("-")
    return s or "item"

def write(path, content):
    """path is site-relative, e.g. 'properties/index.html'."""
    full = os.path.join(DIST, path)
    d = os.path.dirname(full)
    if d and not os.path.isdir(d):
        os.makedirs(d)
    with open(full, "w") as f:
        f.write(content)
    return full

