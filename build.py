def copy_assets():
    """Copies assets, leaving internal notes behind. README files in the asset
    tree are instructions for whoever supplies the artwork, not site content."""
    src = os.path.join(ROOT, "assets")
    dst = os.path.join(DIST, "assets")
    if os.path.isdir(dst):
        shutil.rmtree(dst)
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns(
        "*.md", ".DS_Store", "*.psd", "*.ai", "Thumbs.db"))
    n = sum(len(f) for _, _, f in os.walk(dst))
    return n


