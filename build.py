def photo(slot, alt, w, h, eager=False, sizes="100vw", cls="", placeholder_alt=None):
    """Emits an <img> for a named slot.

    If tools_process_photos.py has produced real photography for the slot, this
    renders a responsive srcset. Otherwise it falls back to the generated SVG
    placeholder and uses alt text that says plainly the image is a placeholder,
    so a screen reader is never told a photograph exists when one does not."""
    # Callers may pass either a bare slot name ("hero-buy") or a legacy asset
    # path ("/assets/img/hero-buy.svg"). Normalise to the slot name.
    if "/" in slot or slot.endswith(".svg"):
        slot = os.path.splitext(os.path.basename(slot))[0]

    p = PHOTOS.get(slot)
    cls_attr = ' class="%s"' % e(cls) if cls else ""
    load_attr = 'eager" fetchpriority="high' if eager else "lazy"

    if p and p.get("sizes"):
        srcset = ", ".join("%s %dw" % (s["src"], s["w"]) for s in p["sizes"])
        largest = p["sizes"][-1]["src"]
        return (
          '<img%s src="%s" srcset="%s" sizes="%s" width="%d" height="%d" '
          'alt="%s" loading="%s" decoding="async">'
        ) % (cls_attr, e(largest), e(srcset), e(sizes), p["width"], p["height"],
             e(p.get("alt") or alt), load_attr)

    return (
      '<img%s src="/assets/img/%s.svg" width="%d" height="%d" alt="%s" '
      'loading="%s" decoding="async">'
    ) % (cls_attr, e(slot), w, h,
         e(placeholder_alt if placeholder_alt is not None else alt), load_attr)


def has_photo(slot):
    return bool(PHOTOS.get(slot, {}).get("sizes"))


