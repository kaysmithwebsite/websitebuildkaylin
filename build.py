# =============================================================================
HREF_RE = re.compile(r'href="([^"]+)"')

def check_links():
    known = set(r["url"] for r in ROUTES)
    if os.path.isfile(os.path.join(DIST, "sitemap.xml")):
        known.add("/sitemap.xml")
    known.add("/robots.txt")
    broken = []
    checked = 0
    for r in ROUTES:
        full = os.path.join(DIST, r["path"])
        if not os.path.isfile(full):
            broken.append((r["url"], r["path"], "page file missing"))
            continue
        with open(full) as f:
            doc = f.read()
        for href in set(HREF_RE.findall(doc)):
            if href.startswith(("http://", "https://", "mailto:", "tel:", "sms:", "#", "data:")):
                continue
            checked += 1
            target = href.split("#")[0].split("?")[0]
            if not target:
                continue
            if target in known:
                continue
            # static asset?
            candidate = os.path.join(DIST, target.lstrip("/"))
            if os.path.isfile(candidate):
                continue
            if os.path.isfile(os.path.join(candidate, "index.html")):
                continue
            broken.append((r["url"], href, "target not found"))
    return checked, broken


def check_overflow_risks():
    """Cheap static guard: flag inline styles that can force horizontal overflow."""
    hits = []
    for r in ROUTES:
        full = os.path.join(DIST, r["path"])
        if not os.path.isfile(full):
            continue
        with open(full) as f:
            doc = f.read()
        for m in re.finditer(r'style="[^"]*width:\s*([4-9]\d{2,}|\d{4,})px', doc):
            hits.append((r["url"], m.group(0)[:70]))
    return hits


