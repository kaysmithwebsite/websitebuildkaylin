def build_sitemap():
    if PREVIEW:
        return 0
    urls = []
    for r in sorted(ROUTES, key=lambda x: -x["priority"]):
        if r["noindex"]:
            continue
        urls.append(
          "  <url>\n    <loc>%s</loc>\n%s    <changefreq>%s</changefreq>\n"
          "    <priority>%.1f</priority>\n  </url>"
          % (e(BASE + r["url"]),
             "    <lastmod>%s</lastmod>\n" % e(r["lastmod"]) if r["lastmod"] else "",
             e(r["changefreq"]), r["priority"]))
    write("sitemap.xml",
      '<?xml version="1.0" encoding="UTF-8"?>\n'
      '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n%s\n</urlset>\n'
      % "\n".join(urls))
    return len(urls)


