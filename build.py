_LOGO_DIMS = {}
def _logo_dims(path):
    """Reads the asset's real pixel dimensions once, via sips."""
    if path in _LOGO_DIMS:
        return _LOGO_DIMS[path]
    full = os.path.join(ROOT, path.lstrip("/"))
    w = h = 0
    try:
        import subprocess
        raw = subprocess.check_output(
            ["sips", "-g", "pixelWidth", "-g", "pixelHeight", full],
            stderr=subprocess.STDOUT).decode("utf-8", "replace")
        for line in raw.splitlines():
            if "pixelWidth" in line:  w = int(line.split(":")[1].strip())
            if "pixelHeight" in line: h = int(line.split(":")[1].strip())
    except Exception:
        pass
    if not w or not h:
        w, h = 1920, 354          # sensible fallback for a wordmark lockup
        warn("BROKERAGE: could not read the logo's pixel dimensions; using a fallback aspect "
             "ratio. Check the asset if the footer lockup looks wrong.")
    _LOGO_DIMS[path] = (w, h)
    return w, h


def _find_brokerage_logo():
    """Uses brokerage.logo_path when set, otherwise picks up an official asset
    dropped into assets/img/brokerage/ automatically, so supplying the file is
    the only step required."""
    configured = BROK.get("logo_path", "")
    if configured:
        return configured
    for name in ("remax-logo.svg", "remax-logo.png", "remax-logo.webp"):
        if os.path.isfile(os.path.join(ROOT, "assets", "img", "brokerage", name)):
            return "/assets/img/brokerage/" + name
    return ""


def _find_brand_logo(key):
    cfg = SITE["brands"][key]
    if cfg.get("logo_path"):
        return cfg["logo_path"]
    stem = "kaylin-real-estate" if key == "real_estate" else "kaylin-consulting"
    for ext in (".svg", ".png", ".webp"):
        if os.path.isfile(os.path.join(ROOT, "assets", "img", "brand", stem + ext)):
            return "/assets/img/brand/" + stem + ext
    return ""


def brand_lockup(key="real_estate", href="/", cls=""):
    """The site carries two brands. Real estate leads everywhere except the
    consulting section, which gets Consulting Group. Neither logo file has been
    supplied, so both render as typographic lockups built from the site's own
    type system. A supplied file replaces the lockup with no other change."""
    cfg = SITE["brands"][key]
    path = _find_brand_logo(key)
    label = "%s %s" % (cfg["name"], cfg["descriptor"])
    if path:
        w, h = _logo_dims(path)
        light = cfg.get("logo_path_light", "")
        # Two colourways where both exist: the reversed mark sits over the hero
        # imagery, the dark one takes over once the bar settles to white. A white
        # lockup on a white bar would simply disappear.
        if light and os.path.isfile(os.path.join(ROOT, light.lstrip("/"))):
            lw, lh = _logo_dims(light)
            return ('<a class="brand brand--img brand--%s brand--dual %s" href="%s" '
                    'aria-label="%s, home">'
                    '<img class="brand__mark brand__mark--light" src="%s" alt="%s" '
                    'width="%d" height="%d" decoding="async">'
                    '<img class="brand__mark brand__mark--dark" src="%s" alt="" aria-hidden="true" '
                    'width="%d" height="%d" decoding="async"></a>'
                    % ("re" if key == "real_estate" else "cons", e(cls), e(href), e(label),
                       e(light), e(cfg["logo_alt"]), lw, lh, e(path), w, h))
        return ('<a class="brand brand--img brand--%s %s" href="%s" aria-label="%s, home">'
                '<img class="brand__mark" src="%s" alt="%s" width="%d" height="%d" '
                'decoding="async"></a>'
                % ("re" if key == "real_estate" else "cons", e(cls), e(href), e(label),
                   e(path), e(cfg["logo_alt"]), w, h))
    if not PRODUCTION:
        warn("BRAND: no %s logo supplied. A typographic lockup is used instead. Drop the file at "
             "assets/img/brand/%s.svg and it replaces the lockup automatically."
             % (cfg["descriptor"], "kaylin-real-estate" if key == "real_estate" else "kaylin-consulting"))
    return ('<a class="brand %s" href="%s" aria-label="%s, home">'
            '<span class="brand__name">%s</span>'
            '<span class="brand__role">%s</span></a>'
            % (e(cls), e(href), e(label), e(cfg["lockup"]), e(cfg["sub"])))


def realtor_marks(on_dark=False):
    """REALTOR and MLS are CREA trademarks. Like the RE/MAX logo, they are never
    drawn here: they come from CREA's official brand assets, available to members
    through their board. Text attribution in the legal block already satisfies the
    trademark notice; the marks themselves are a brand asset."""
    out = []
    for name, alt in (("realtor", "REALTOR\u00ae"), ("mls", "MLS\u00ae")):
        found = ""
        for ext in (".svg", ".png", ".webp"):
            p = os.path.join(ROOT, "assets", "img", "brokerage", name + ext)
            if os.path.isfile(p):
                found = "/assets/img/brokerage/" + name + ext
                break
        if found:
            out.append('<img class="mark" src="%s" alt="%s" height="26" loading="lazy" '
                       'decoding="async">' % (e(found), e(alt)))
    if out:
        return '<div class="marks">%s</div>' % "".join(out)
    if PRODUCTION:
        return ""
    warn("TRADEMARKS: no REALTOR or MLS logo asset is present. Both are CREA trademarks and are "
         "not redrawn by this build. Request the official assets through TRREB and place them at "
         "assets/img/brokerage/realtor.svg and mls.svg. The written trademark attribution in the "
         "footer already satisfies the disclosure requirement meanwhile.")
    return ('<div class="marks"><span class="bid__logoslot%s">'
            'Official REALTOR&reg; and MLS&reg; marks required<br>'
            '<small>assets/img/brokerage/realtor.svg</small></span></div>'
            % (" bid__logoslot--dark" if on_dark else ""))


