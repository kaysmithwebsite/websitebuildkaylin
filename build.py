_ASSET_V = {}
def asset(path):
    """Returns /assets/... with a short content hash, so caches invalidate on change."""
    if path not in _ASSET_V:
        full = os.path.join(ROOT, path.lstrip("/"))
        try:
            import hashlib
            with open(full, "rb") as f:
                _ASSET_V[path] = hashlib.sha1(f.read()).hexdigest()[:8]
        except IOError:
            _ASSET_V[path] = "0"
    return "%s?v=%s" % (path, _ASSET_V[path])

